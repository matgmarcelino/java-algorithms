/*
 * Defines the DeckType enum, which identifies whether a Deck is the Chance
 * deck or the Community Chest deck.
 */

package cards;

/**
 * Which of the two card decks a {@link Deck} represents.
 */
public enum DeckType {
    /** The Chance deck. */
    CHANCE,
    /** The Community Chest deck. */
    COMMUNITY_CHEST
}
